// Quote a product. Returns { annual, semiannual, monthly, lines[], notes[] } or null when the
// inputs don't reach a rate (e.g. age outside the table) — callers fall back to manual entry.
export function quotePremium(key, opts = {}) {
  const { tier = 1, age, occClass = "12", gender = "male", smoker = false, riders = {} } = opts;
  const meta = RATED_PRODUCTS[key];
  if (!meta) return null;
  const t = Math.min(Math.max(Number(tier) || 1, 1), meta.tiers);
  const i = t - 1;
  const lines = [], notes = [];
  const add = (label, rates) => {
    const s = split(rates, meta.tiers);
    if (!s) return false;
    lines.push({ label, annual: s.annual[i], semiannual: s.semiannual[i], monthly: s.monthly[i] });
    return true;
  };

  if (key === "PA") {
    const a = Number(age);
    if (!(a >= 16 && a <= 74)) return null;
    const cls = String(occClass) === "34" ? "34" : "12";
    if (!add("Basic Benefits", pickBand(PA_RATES[cls].basic, a))) return null;
    if (riders.lifestyle) add("Lifestyle Maintenance", pickBand(PA_RATES[cls].lifestyle, a));
    if (riders.hospital) add("Accidental Hospitalisation", pickBand(PA_RATES[cls].hospital, a));
    if (a > 65) notes.push("Ages 66-74 are renewal-only rates — not available for new entry.");
  } else if (key === "HI") {
    const a = Number(age);
    if (!(a >= 1 && a <= 84)) return null;
    if (!add("Hospital Income", pickBand(HI_RATES, a))) return null;
    if (a > 75) notes.push("Ages 76-84 are renewal-only rates.");
  } else if (key === "SA") {
    add("Basic Benefits", SA_BASIC);
    if (riders.childCI) add("Child Critical Illnesses", SA_CHILD_CI);
    const a = Number(age);
    if (a > 16) notes.push("Star Armour entry age is 16 and below.");
  } else if (key === "CPA") {
    const a = Number(age);
    if (!(a >= 40 && a <= 99)) return null;
    if (!add("Basic Benefits", pickBand(CPA_BASIC, a))) return null;
    if (riders.dementia) {
      const g = (gender === "female" ? "female" : "male") + "_" + (smoker ? "smoker" : "nonsmoker");
      const row = pickBand(CPA_DEMENTIA[g] || [], a);
      if (row) add("Dementia Benefits", row);
      else notes.push("Dementia cover is rated to age 84 only — no rider premium beyond that.");
    }
    if (a > 80) notes.push("Ages 81+ are renewal-only rates — not available for new entry.");
  } else return null;

  if (!lines.length) return null;
  const sum = (f) => Math.round(lines.reduce((s, l) => s + (l[f] || 0), 0) * 100) / 100;
  return { annual: sum("annual"), semiannual: sum("semiannual"), monthly: sum("monthly"), lines, notes, currency: meta.currency };
}

