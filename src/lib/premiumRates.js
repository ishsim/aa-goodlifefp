// Coverage rows for a tier + rider selection, shaped like the editor's coverage breakdown.
export function benefitsFor(key, tier, riders = {}, riderOpts = {}) {
  const b = PLAN_BENEFITS[key];
  if (!b) return null;
  const max = RATED_PRODUCTS[key].tiers;
  const i = Math.min(Math.max(Number(tier) || 1, 1), max) - 1;
  const rows = b.base.map(([c, a]) => [c, a[i]]);
  Object.entries(b.riders).forEach(([k, defs]) => {
    if (!riders[k]) return;
    const j = Math.min(Math.max(Number(riderOpts[k]) || (i + 1), 1), max) - 1;
    defs.forEach(([c, a]) => rows.push([c, a[j]]));
  });
  return rows.map(([category, amount]) => ({ category, amount: String(amount) }));
}
