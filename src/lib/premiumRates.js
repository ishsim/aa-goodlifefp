// Coverage rows for a tier + rider selection, shaped like the editor's coverage breakdown.
export function benefitsFor(key, tier, riders = {}) {
  const b = PLAN_BENEFITS[key];
  if (!b) return null;
  const i = Math.min(Math.max(Number(tier) || 1, 1), RATED_PRODUCTS[key].tiers) - 1;
  const rows = [...b.base];
  Object.entries(b.riders).forEach(([k, defs]) => { if (riders[k]) rows.push(...defs); });
  return rows.map(([category, amts]) => ({ category, amount: String(amts[i]) }));
}
